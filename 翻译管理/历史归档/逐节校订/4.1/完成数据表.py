arrays=[x for x in blocks if '\\begin{array}' in x]
def arraytable(i):
    tex=re.sub(r'^\s*\\begin\{array\}\{[^}]*\}\s*','',arrays[i]); a=0; z=tex.rindex('\\end{array}')
    lines=tex[a:z].replace('\\hline','').strip().split('\\\\')
    rows=[[c.strip() for c in row.strip().split('&')] for row in lines if row.strip()]
    count=len(rows[0]); rows=[r+['']*(count-len(r)) for r in rows]
    return '\n'.join(['| '+' | '.join('$'+norm(c)+'$' if c else '' for c in row)+' |' for row in rows[:1]]+['|'+'---|'*count]+['| '+' | '.join('$'+norm(c)+'$' if c else '' for c in row)+' |' for row in rows[1:]])+'\n\n'

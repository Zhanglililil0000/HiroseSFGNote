 s=s.replace('（旧译待校订）：回顾本组内容的要点。（全节译校完成）：','（全节译校完成）：')
 s=s.replace('**本章导读（待正文核验）：** 转向双层膜体系及其一般表达式。','**本章导读：** 3.1讨论二层膜与三层膜的和频出射场，3.2整理双层膜的一般式及附录。先确认源层与传播方向，再选择对应表达式；两节均完成本轮译校，原式疑点保留。')
 s=s.replace('**本章导读（待正文核验）：** 按基团取向与对称性组织张量分量的讨论。','**本章导读：** 4.1建立CH伸缩响应，4.2—4.4分别讨论CH₃、CH₂、CH取向，4.5—4.7处理双基团与对称性变化，4.8—4.9讨论氢化金刚石表面，4.10—4.11查欧拉角与坐标旋转。全章完成本轮译校，各体系的角度与坐标定义仍按各节保留。')
 # Canonical titles in directory labels; do not touch the body subsection lists.
 for r in rows:
  title=Path(r['现有译文路径']).stem
  s=re.sub(r'(?m)^- \['+re.escape(r['编号'])+r' [^\]]+\](\([^\n]+?\))',lambda m:'- ['+title+']'+m[1],s)
 s=s.replace('## 导读的定稿要求','## 导读的维护要求').replace('每节正文核验后，将标题级概括替换为','本轮39节正文均已完成译校，目录按现行文件名排列。后续修订时继续维护')
 s=s.replace('旧文件名“CH弯曲振动”仅为链接兼容保留。','旧文件名“CH弯曲振动”已在文件命名整理中更正。')

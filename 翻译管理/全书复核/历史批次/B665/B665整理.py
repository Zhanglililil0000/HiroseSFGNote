from pathlib import Path
import csv,re,json,shutil
R=Path(__file__).resolve().parents[2]; O=R/'翻译管理/全书复核'; backup=O/'B665修改前'
rows=list(csv.DictReader((R/'翻译管理/章节清单.tsv').open(encoding='utf-8-sig'),delimiter='\t'))
changes=[]
def edit(rel,fn):
 p=R/rel; old=p.read_text(encoding='utf-8-sig'); new=fn(old)
 if new!=old:
  b=backup/rel;b.parent.mkdir(parents=True,exist_ok=True)
  if not b.exists():shutil.copy2(p,b)
  p.write_text(new,encoding='utf-8');changes.append(rel)
